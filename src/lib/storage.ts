import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Product image storage.
 *
 * Images uploaded in the admin panel are written to UPLOAD_DIR on the server's
 * disk and served from /uploads/<file> (see src/app/uploads/[...path]/route.ts).
 *
 * To use a cloud provider instead (S3, Cloudinary, Vercel Blob...), replace
 * the bodies of saveImage / deleteImage / readImage — nothing else in the app
 * depends on where the files live, only on the URL that saveImage returns.
 */

export const MAX_IMAGE_BYTES = 5 * 1024 * 1024; // 5 MB
export const PUBLIC_UPLOAD_PREFIX = "/uploads/";

const IMAGE_TYPES = {
  jpg: "image/jpeg",
  png: "image/png",
  webp: "image/webp",
} as const;

type ImageExt = keyof typeof IMAGE_TYPES;

function uploadDir() {
  return path.resolve(process.cwd(), process.env.UPLOAD_DIR ?? "./uploads");
}

/** Detects the real file type from its first bytes rather than trusting the filename. */
function detectImageType(bytes: Uint8Array): ImageExt | null {
  if (bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) return "jpg";
  if (bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4e && bytes[3] === 0x47) return "png";
  const riff = String.fromCharCode(...bytes.slice(0, 4));
  const webp = String.fromCharCode(...bytes.slice(8, 12));
  if (riff === "RIFF" && webp === "WEBP") return "webp";
  return null;
}

export class UploadError extends Error {}

export async function saveImage(file: File): Promise<string> {
  if (file.size === 0) throw new UploadError("The selected file is empty.");
  if (file.size > MAX_IMAGE_BYTES) throw new UploadError("Images must be 5 MB or smaller.");

  const bytes = new Uint8Array(await file.arrayBuffer());
  const ext = detectImageType(bytes);
  if (!ext) throw new UploadError("Only JPG, PNG and WebP images are supported.");

  const dir = uploadDir();
  await mkdir(dir, { recursive: true });
  const filename = `${randomUUID()}.${ext}`;
  await writeFile(path.join(dir, filename), bytes);
  return `${PUBLIC_UPLOAD_PREFIX}${filename}`;
}

/** Removes an uploaded image. URLs that are not uploads (e.g. bundled demo images) are ignored. */
export async function deleteImage(url: string): Promise<void> {
  if (!url.startsWith(PUBLIC_UPLOAD_PREFIX)) return;
  const filename = safeFilename(url.slice(PUBLIC_UPLOAD_PREFIX.length));
  if (!filename) return;
  await unlink(path.join(uploadDir(), filename)).catch(() => undefined);
}

export async function readImage(filename: string) {
  const name = safeFilename(filename);
  if (!name) return null;
  const ext = name.split(".").pop() as ImageExt;
  try {
    const data = await readFile(path.join(uploadDir(), name));
    return { data, contentType: IMAGE_TYPES[ext] };
  } catch {
    return null;
  }
}

/** Only allows the UUID-based names generated by saveImage (blocks path traversal). */
function safeFilename(name: string): string | null {
  return /^[a-f0-9-]{36}\.(jpg|png|webp)$/.test(name) ? name : null;
}
